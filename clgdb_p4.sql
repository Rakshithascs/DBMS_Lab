-- Q4: Calculate FinalIA = Avg of Best 2 Tests and Update (CORRECTED)
SET SQL_SAFE_UPDATES = 0;

UPDATE IAMARKS
SET FinalIA = (Test1 + Test2 + Test3 - LEAST(Test1, Test2, Test3)) / 2;

SET SQL_SAFE_UPDATES = 1;

SELECT USN, Subcode, Test1, Test2, Test3, FinalIA FROM IAMARKS;

-- Q5: Categorize 8th Sem A, B, C Students
SELECT S.USN, S.SName, SS.Sem, SS.Sec, I.Subcode, I.FinalIA,
CASE
    WHEN I.FinalIA >= 17 THEN 'Outstanding'
    WHEN I.FinalIA >= 12 THEN 'Average'
    ELSE 'Weak'
END AS CAT
FROM STUDENT S, CLASS C, SEMSEC SS, IAMARKS I
WHERE S.USN = C.USN
AND C.SSID = SS.SSID
AND S.USN = I.USN
AND I.SSID = SS.SSID
AND SS.Sem = 8
AND SS.Sec IN ('A', 'B', 'C');
