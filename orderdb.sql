-- Q1. Count the customers
-- with grades above Bangalore's average.
SELECT COUNT(*) AS CUSTOMER_COUNT
FROM CUSTOMER
WHERE GRADE > (
    SELECT AVG(GRADE)
    FROM CUSTOMER
    WHERE CITY = 'BANGALORE'
);

-- Q2. Find the name and numbers
-- of all salesman who had more than one customer.
SELECT S.SALESMAN_ID,
       S.NAME,
       COUNT(C.CUSTOMER_ID) AS NO_OF_CUSTOMERS
FROM SALESMAN S, CUSTOMER C
WHERE S.SALESMAN_ID = C.SALESMAN_ID
GROUP BY S.SALESMAN_ID, S.NAME
HAVING COUNT(C.CUSTOMER_ID) > 1;

-- Q3. List all the salesman and indicate
-- those who have and don't have customers in their cities (Use UNION).
SELECT DISTINCT S.NAME AS SALESMAN_NAME,
       S.CITY,
       'HAS CUSTOMER' AS STATUS
FROM SALESMAN S, CUSTOMER C
WHERE S.CITY = C.CITY

UNION

SELECT S.NAME AS SALESMAN_NAME,
       S.CITY,
       'NO CUSTOMER' AS STATUS
FROM SALESMAN S
WHERE S.CITY NOT IN (
    SELECT C.CITY
    FROM CUSTOMER C
);

-- Q4. Create a view that finds
-- the salesman who has the customer with the highest order of a day.
CREATE VIEW V_HIGH_ORDER AS
SELECT S.NAME AS SALESMAN_NAME,
       C.CUST_NAME AS CUSTOMER_NAME,
       O.PURCHASE_AMT,
       O.ORD_DATE
FROM SALESMAN S, CUSTOMER C, ORDERS O
WHERE S.SALESMAN_ID = O.SALESMAN_ID
AND C.CUSTOMER_ID = O.CUSTOMER_ID
AND O.PURCHASE_AMT = (
    SELECT MAX(O2.PURCHASE_AMT)
    FROM ORDERS O2
    WHERE O2.ORD_DATE = O.ORD_DATE
);
SELECT * FROM V_HIGH_ORDER;

