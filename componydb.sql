DROP DATABASE IF EXISTS CompanyDatabase;
CREATE DATABASE CompanyDatabase;
USE CompanyDatabase;

CREATE TABLE EMPLOYEE (
    SSN VARCHAR(10) PRIMARY KEY,
    Name VARCHAR(30),
    Address VARCHAR(50),
    Sex VARCHAR(10),
    Salary DECIMAL(10,2),
    SuperSSN VARCHAR(10),
    DNo INT
);

CREATE TABLE DEPARTMENT (
    DNo INT PRIMARY KEY,
    DName VARCHAR(30),
    MgrSSN VARCHAR(10),
    MgrStartDate DATE
);

CREATE TABLE DLOCATION (
    DNo INT,
    DLoc VARCHAR(30),
    PRIMARY KEY (DNo, DLoc)
);

CREATE TABLE PROJECT (
    PNo INT PRIMARY KEY,
    PName VARCHAR(30),
    PLocation VARCHAR(30),
    DNo INT
);

CREATE TABLE WORKS_ON (
    SSN VARCHAR(10),
    PNo INT,
    Hours DECIMAL(5,2),
    PRIMARY KEY (SSN, PNo)
);

