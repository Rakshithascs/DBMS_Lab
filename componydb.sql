-- Q1: Project numbers for Scott - as worker OR as manager
SELECT P.PNo
FROM PROJECT P, WORKS_ON W, EMPLOYEE E
WHERE P.PNo = W.PNo
AND W.SSN = E.SSN
AND E.Name = 'Scott'
UNION
SELECT P.PNo
FROM PROJECT P, DEPARTMENT D, EMPLOYEE E
WHERE P.DNo = D.DNo
AND D.MgrSSN = E.SSN
AND E.Name = 'Scott';

-- Q2: Show resulting salaries if IoT employees get 10% raise
SELECT E.Name,
       E.Salary AS OLD_SALARY,
       E.Salary * 1.10 AS NEW_SALARY
FROM EMPLOYEE E, WORKS_ON W, PROJECT P
WHERE E.SSN = W.SSN
AND W.PNo = P.PNo
AND P.PName = 'IoT';

-- Q3: SUM, MAX, MIN, AVG for Accounts dept
SELECT SUM(E.Salary) AS TOTAL_SALARY,
       MAX(E.Salary) AS MAX_SALARY,
       MIN(E.Salary) AS MIN_SALARY,
       AVG(E.Salary) AS AVG_SALARY
FROM EMPLOYEE E, DEPARTMENT D
WHERE E.DNo = D.DNo
AND D.DName = 'Accounts';

-- Q4: Employees who work on ALL projects of Dept 5 - NOT EXISTS
SELECT E.Name
FROM EMPLOYEE E
WHERE NOT EXISTS (
    SELECT P.PNo
    FROM PROJECT P
    WHERE P.DNo = 5
    AND NOT EXISTS (
        SELECT W.PNo
        FROM WORKS_ON W
        WHERE W.SSN = E.SSN
        AND W.PNo = P.PNo
    )
);

-- Q5: Dept with >5 employees, count Salary > 600000
SELECT DNo,
       COUNT(*) AS HIGH_SALARY_EMPLOYEES
FROM EMPLOYEE
WHERE Salary > 600000
AND DNo IN (
    SELECT DNo
    FROM EMPLOYEE
    GROUP BY DNo
    HAVING COUNT(*) > 5
)
GROUP BY DNo;
